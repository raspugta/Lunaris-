"""Generate the small, deterministic SYNTHETIC demo fixture (used by CI and demo mode).

Everything written here is synthetic and labelled as such in its GeoTIFF tags.
It does not describe any real lunar location. The grid is given a south polar
stereographic transform so that the full pipeline (including lat/lon readouts)
is exercised, but coordinates are fictitious.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import rasterio
from rasterio.transform import from_origin

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core.geospatial.grid import polar_stereo_south_inverse  # noqa: E402

N, RES = 320, 40.0  # 12.8 km square at 40 m
CRS = "+proj=stere +lat_0=-90 +lon_0=0 +k=1 +x_0=0 +y_0=0 +R=1737400 +units=m +no_defs"


def crater(xx, yy, cx, cy, r, depth):
    d = np.hypot(xx - cx, yy - cy) / r
    bowl = np.where(d < 1.0, -depth * (1 - d ** 2), 0.0)
    rim = 0.18 * depth * np.exp(-((d - 1.0) / 0.22) ** 2)
    return bowl + rim


def make(out_dir: Path) -> None:
    rng = np.random.default_rng(42)
    x = (np.arange(N) + 0.5) * RES - N * RES / 2
    y = (N * RES / 2) - (np.arange(N) + 0.5) * RES
    xx, yy = np.meshgrid(x, y)
    z = 0.015 * xx + 0.004 * yy  # regional tilt
    z += crater(xx, yy, 1200, -900, 3200, 900)
    for _ in range(40):
        cx, cy = rng.uniform(-6000, 6000, 2)
        r = rng.uniform(80, 700)
        z += crater(xx, yy, cx, cy, r, 0.2 * r)
    z += rng.normal(0, 0.6, z.shape)
    z = z.astype(np.float32)
    z[40:52, 250:270] = np.nan  # an explicit no-data gap
    psr = (crater(xx, yy, 1200, -900, 3200, 900) < -500).astype(np.float32)
    tmax = np.where(psr > 0, 60 + 40 * (np.hypot(xx - 1200, yy + 900) / 2400), 220).astype(np.float32)
    tmax = np.clip(tmax, 40, 300) + rng.normal(0, 2, tmax.shape).astype(np.float32)
    out_dir.mkdir(parents=True, exist_ok=True)
    transform = from_origin(-N * RES / 2, N * RES / 2, RES, RES)
    for name, arr in [("synthetic_dem.tif", z), ("synthetic_psr.tif", psr), ("synthetic_tmax.tif", tmax)]:
        with rasterio.open(out_dir / name, "w", driver="GTiff", height=N, width=N, count=1, dtype="float32",
                           crs=CRS, transform=transform, nodata=np.nan, compress="deflate") as dst:
            dst.write(arr, 1)
            dst.update_tags(SYNTHETIC="true", NOTE="Synthetic demo data generated by scripts/make_demo_fixture.py; not lunar data")
    lat, lon = polar_stereo_south_inverse(0, 0)
    print(f"wrote synthetic fixture to {out_dir} (centre lat {float(lat):.2f})")


if __name__ == "__main__":
    make(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data" / "demo")
